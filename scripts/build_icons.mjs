// Builds silk/templates/silk/inclusion/icon_sprite.html: an inline SVG sprite
// holding only the Lucide icons Silk uses, so pages need no icon JavaScript.
//
//   npm run icons
//
// Icons come from two places: every data-icon="name" or href="#i-name" in the templates and JS,
// plus EXTRA for icons referenced only from Python or built dynamically.

import { readFileSync, readdirSync, statSync, writeFileSync } from 'node:fs';
import { join } from 'node:path';
import * as lucide from 'lucide';

const EXTRA = ['chevron-up', 'copy', 'search', 'panel-left', 'list', 'flame', 'git-compare', 'timer', 'list-ordered', 'layout-dashboard'];
const ROOTS = ['silk/templates', 'silk/static/silk/js'];
const OUT = 'silk/templates/silk/inclusion/icon_sprite.html';

const walk = (dir) => readdirSync(dir).flatMap((f) => {
  const p = join(dir, f);
  return statSync(p).isDirectory() ? walk(p) : [p];
});

const names = new Set(EXTRA);
for (const file of ROOTS.flatMap(walk)) {
  if (file.endsWith('icon_sprite.html')) continue;
  const text = readFileSync(file, 'utf8');
  for (const m of text.matchAll(/data-icon="([a-z0-9-]+)"|href="#i-([a-z0-9-]+)"|setIcon\([^,]+,\s*'([a-z0-9-]+)'\)/g)) names.add(m[1] || m[2] || m[3]);
}

const pascal = (n) => n.replace(/(^|-)([a-z0-9])/g, (_, __, c) => c.toUpperCase());
const attrs = (o) => Object.entries(o).map(([k, v]) => `${k}="${v}"`).join(' ');

const symbols = [...names].sort().map((name) => {
  const node = lucide.icons?.[pascal(name)] || lucide[pascal(name)];
  if (!node) throw new Error(`Unknown Lucide icon: ${name}`);
  const children = node.map(([tag, a]) => `<${tag} ${attrs(a)}/>`).join('');
  // Presentation attributes go on each symbol: <use> clones the symbol, not the sprite's root.
  return `<symbol id="i-${name}" viewBox="0 0 24 24" fill="none" stroke="currentColor" stroke-width="2" stroke-linecap="round" stroke-linejoin="round">${children}</symbol>`;
});

writeFileSync(OUT, `{# Generated by scripts/build_icons.mjs (npm run icons). Do not edit by hand. #}
<svg xmlns="http://www.w3.org/2000/svg" style="display:none" aria-hidden="true">
${symbols.join('\n')}
</svg>
`);
console.log(`wrote ${OUT}: ${symbols.length} icons`);
